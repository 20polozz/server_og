for k = 0, 63 do
    local bits, caras = "", 0
    for i = 5, 0, -1 do
        local b = math.floor(k / 2 ^ i) % 2
        bits = bits .. ("%d"):format(b)
        caras = caras + b
    end
    if caras >= 2 then
        MODELS[joaat("origen_casa_cubo_" .. bits)] = true
    end
end

-- spawn one in front of the player for testing: /prop_phone_charger
RegisterCommand("prop_phone_charger", function()
    local model = joaat("prop_phone_charger")

    if not IsModelInCdimage(model) then
        print("^1[prop_phone_charger] model not in game files — is the resource started & .ytyp present?^0")
        return
    end

    RequestModel(model)
    local tries = 0
    while not HasModelLoaded(model) and tries < 500 do   -- up to ~5s for first stream
        Wait(10)
        tries = tries + 1
    end

    if not HasModelLoaded(model) then
        print("^1[prop_phone_charger] model failed to load^0")
        return
    end

    local ped = PlayerPedId()
    local fwd = GetEntityForwardVector(ped)
    local pos = GetEntityCoords(ped) + (fwd * 2.0)

    -- request collision at the target so the embedded bound streams in
    RequestCollisionAtCoord(pos.x, pos.y, pos.z)

    local obj = CreateObject(model, pos.x, pos.y, pos.z, true, true, false)
    SetEntityAsMissionEntity(obj, true, true)
    SetEntityHeading(obj, GetEntityHeading(ped))
    PlaceObjectOnGroundProperly(obj)

    -- KEY: force collision on + freeze so it is a solid static prop (won't fall / can't walk through)
    SetEntityCollision(obj, true, true)
    FreezeEntityPosition(obj, true)

    SetModelAsNoLongerNeeded(model)
    print(("^2[prop_phone_charger] spawned at %.1f %.1f %.1f^0"):format(pos.x, pos.y, pos.z))
end, false)

AddEventHandler("onResourceStop", function(resource)
    if resource ~= GetCurrentResourceName() then
        return
    end

    local pool = GetGamePool("CObject")

    for i = #pool, 1, -1 do
        local obj = pool[i]

        if DoesEntityExist(obj) and MODELS[GetEntityModel(obj)] then
            SetEntityAsMissionEntity(obj, true, true)
            DeleteObject(obj)

            if DoesEntityExist(obj) then
                DeleteEntity(obj)
            end
        end
    end

    for hash in pairs(MODELS) do
        SetModelAsNoLongerNeeded(hash)
    end

    collectgarbage("collect")
end)
