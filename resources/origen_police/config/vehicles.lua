local tempVehicles = {}

for k, v in pairs(Config.Vehicles) do
    tempVehicles[k] = {}
    for job, vehicles in pairs(v) do
        tempVehicles[k][job] = {}
        for vehicle, vehicleData in pairs(vehicles) do
            local hashKey = GetHashKey(vehicle)
            tempVehicles[k][job][hashKey] = vehicleData
        end
    end
end

